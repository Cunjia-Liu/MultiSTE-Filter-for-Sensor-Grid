function sources = source_configurations(index,nTrueSources)
%SOURCE_CONFIGURATIONS Five existing benchmark presets; rows [Q; x; y].
% Q is in g/s and x,y in m. Use cfg.sourceMode='custom' for other layouts.
if nargin < 2, nTrueSources = 3; end
validateattributes(index,{'numeric'},{'scalar','integer','>=',1,'<=',5});
validateattributes(nTrueSources,{'numeric'},{'scalar','integer','>=',1,'<=',4});
presets = cat(3, ...
    [6 7 11 9; 15 40 25 15; 40 30 20 20], ...
    [5 9 8 10; 40 15 25 10; 30 45 20 18], ...
    [7 7 11 9; 5 30 25 20; 30 10 40 20], ...
    [9 4 9 11; 10 25 35 15; 40 25 35 20], ...
    [4 6 10 8; 20 30 40 25; 40 30 35 20]);
sources = presets(:,1:nTrueSources,index);
end
